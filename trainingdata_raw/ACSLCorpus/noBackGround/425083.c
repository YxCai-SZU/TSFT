#include <limits.h>

/*@
    requires (-1000000000 <= (a) <= 1000000000) && (-1000000000 <= (b) <= 1000000000) && (-1000000000 <= (c) <= 1000000000) && (-1000000000 <= (d) <= 1000000000);
    requires ((a) <= (b)) && ((c) <= (d));
    requires a <= 9223372036854775807 && a >= -9223372036854775807 - 1;
    requires b <= 9223372036854775807 && b >= -9223372036854775807 - 1;
    requires c <= 9223372036854775807 && c >= -9223372036854775807 - 1;
    requires d <= 9223372036854775807 && d >= -9223372036854775807 - 1;
    ensures \result == a * c || \result == b * c || 
            \result == a * d || \result == b * d;
*/
long long func(long long a, long long b, long long c, long long d) {
    long long x;
    long long temp;
    
    //@ assert (-1000000000 <= (a) <= 1000000000) && (-1000000000 <= (c) <= 1000000000);
    //@ assert (-1000000000000000000 <= (a) * (c) <= 1000000000000000000);
    x = a * c;
    
    //@ assert (-1000000000 <= (b) <= 1000000000) && (-1000000000 <= (c) <= 1000000000);
    //@ assert (-1000000000000000000 <= ((c)) * (c) <= 1000000000000000000);
    temp = b * c;
    
    if (temp > x) {
        x = temp;
    }
    
    //@ assert (-1000000000 <= (a) <= 1000000000) && (-1000000000 <= (d) <= 1000000000);
    //@ assert (-1000000000000000000 <= (a) * (d) <= 1000000000000000000);
    temp = a * d;
    
    if (temp > x) {
        x = temp;
    }
    
    //@ assert (-1000000000 <= (b) <= 1000000000) && (-1000000000 <= (d) <= 1000000000);
    //@ assert (-1000000000000000000 <= ((d)) * (d) <= 1000000000000000000);
    temp = b * d;
    
    if (temp > x) {
        x = temp;
    }
    
    return x;
}
